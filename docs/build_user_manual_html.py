parts = []


def esc(s):
    return H.escape(s, quote=False)


def h1(text):
    parts.append('<h1>%s</h1>' % esc(text))


def h2(text):
    parts.append('<h2>%s</h2>' % esc(text))


def p(text):
    parts.append('<p>%s</p>' % esc(text))


def ul(items):
    parts.append('<ul>%s</ul>' % ''.join('<li>%s</li>' % esc(i) for i in items))


def ol(items):
    parts.append('<ol>%s</ol>' % ''.join('<li>%s</li>' % esc(i) for i in items))


def table(rows, widths):
    head = rows[0]
    body = rows[1:]
    colgroup = ''.join('<col style="width:%s%%">' % w for w in widths)
    th = ''.join('<th>%s</th>' % esc(c) for c in head)
    trs = ''.join('<tr>%s</tr>' % ''.join('<td>%s</td>' % esc(c) for c in r) for r in body)
    parts.append('<table><colgroup>%s</colgroup><thead><tr>%s</tr></thead><tbody>%s</tbody></table>'
                 % (colgroup, th, trs))


def fig(name, caption, cls=""):
    path = os.path.join(SHOT, name)
    if not os.path.exists(path):
        return
    parts.append('<figure class="%s"><img src="../截图/%s" alt=""><figcaption>%s</figcaption></figure>'
                 % (cls, esc(name), esc(caption)))


